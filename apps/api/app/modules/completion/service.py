import asyncio
import json
import urllib.error
import urllib.request
from typing import Protocol
from uuid import uuid4

from app.core.config import Settings
from app.core.errors import DomainError
from app.modules.completion.models import CompletionRequest
from app.platform.admission import AdmissionController
from app.platform.audit import AuditStore
from app.platform.records import RecordingPolicy, RecordStore


class CompletionProvider(Protocol):
    provider_id: str
    model_id: str

    async def complete(self, request: CompletionRequest) -> str: ...


class MockCompletionProvider:
    provider_id = "mock-completion"
    model_id = "deterministic-demo"

    async def complete(self, request: CompletionRequest) -> str:
        # Simple deterministic continuation for testing purposes
        return f"{request.text} [mock continuation text generated by the demo provider]"


class OllamaCompletionProvider:
    provider_id = "ollama-local"

    def __init__(self, base_url: str, model: str) -> None:
        self.base_url = base_url.rstrip("/")
        self.model_id = model

    async def complete(self, request: CompletionRequest) -> str:
        """Send the input text as a raw continuation prompt to Ollama.

        Uses the /api/generate endpoint (not /api/chat) to avoid chat-style
        system/user/assistant framing. The prompt is passed verbatim so the
        model continues the text naturally.
        """
        model = request.model or self.model_id
        body = json.dumps(
            {
                "model": model,
                "prompt": request.text,
                "stream": False,
                "options": {
                    "temperature": request.temperature,
                    "top_p": request.top_p,
                    "num_predict": request.max_tokens,
                },
            }
        ).encode()

        def call() -> str:
            http_request = urllib.request.Request(
                f"{self.base_url}/api/generate",
                data=body,
                headers={"Content-Type": "application/json"},
                method="POST",
            )
            with urllib.request.urlopen(http_request, timeout=60) as response:
                payload = json.load(response)
            if "response" not in payload:
                raise ValueError("Missing 'response' in Ollama generate endpoint payload")
            return str(payload.get("response", ""))

        try:
            return await asyncio.wait_for(asyncio.to_thread(call), timeout=65)
        except TimeoutError as exc:
            raise DomainError(
                "PROVIDER_TIMEOUT",
                "The completion model did not respond in time. Please try again.",
                504,
                True,
            ) from exc
        except urllib.error.HTTPError as exc:
            if exc.code == 404:
                raise DomainError(
                    "MODEL_NOT_FOUND",
                    f"The configured completion model '{self.model_id}' was not found in Ollama. "
                    "Ensure the model has been pulled (ollama pull <model>).",
                    502,
                    False,
                ) from exc
            raise DomainError(
                "PROVIDER_FAILURE",
                f"The completion provider returned HTTP {exc.code}.",
                502,
                True,
            ) from exc
        except urllib.error.URLError as exc:
            raise DomainError(
                "PROVIDER_UNAVAILABLE",
                f"Unable to reach the completion provider at {self.base_url}. "
                "Please check that Ollama is running and accessible.",
                502,
                True,
            ) from exc
        except (KeyError, ValueError) as exc:
            raise DomainError(
                "PROVIDER_FAILURE",
                "The completion provider returned a malformed response.",
                502,
                True,
            ) from exc


def build_completion_provider(settings: Settings) -> CompletionProvider:
    if settings.completion_provider == "mock":
        return MockCompletionProvider()
    if settings.completion_provider == "ollama":
        base_url = settings.completion_base_url or settings.ollama_base_url
        return OllamaCompletionProvider(base_url, settings.completion_model)
    raise RuntimeError(f"Unsupported completion provider: {settings.completion_provider}")


class CompletionService:
    def __init__(
        self,
        provider: CompletionProvider,
        admission: AdmissionController,
        audit: AuditStore,
        records: RecordStore,
    ) -> None:
        self.provider = provider
        self.admission = admission
        self.audit = audit
        self.records = records

    async def complete(
        self,
        request: CompletionRequest,
        owner_id: str,
        policy: RecordingPolicy,
    ) -> dict[str, object]:
        request_id = str(uuid4())
        async with self.admission.admit("completion"):
            continuation = await self.provider.complete(request)
        await self.audit.record(
            actor_id=owner_id,
            action="completion.complete",
            target_type="request",
            target_id=request_id,
            outcome="completed",
        )
        interaction_id = await self.records.create_interaction(
            interaction_id=request_id,
            user_id=owner_id,
            module_id="completion",
            query_text=request.text,
            answer_text=continuation,
            provider_id=self.provider.provider_id,
            model_id=self.provider.model_id,
            language="en",  # completion model handles multilingual natively
            policy=policy,
        )
        return {
            "request_id": request_id,
            "text": continuation,
            "provider_id": self.provider.provider_id,
            "model_id": self.provider.model_id,
            "interaction_id": interaction_id,
        }
